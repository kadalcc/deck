/**
 * The two small files an imported deck carries for what Slidev did and Kadal does not do the
 * same way. Both are written only with what the deck uses.
 *
 *   src/slidev.css   Slidev's rem at Kadal's scale (`--slidev-rem`), Tailwind's spacing and type
 *                    scale set to it (so a utility Tailwind generates matches Slidev's size too),
 *                    the CSS for every utility class the deck uses (uno.ts), Slidev's click
 *                    presets (`v-click.fade.right`) and the `fade-out` transition's keyframes.
 *   src/slidev.tsx   `SlidevOn` (an element that runs a Slidev `$slidev.nav` call on click) and
 *                    `slotsOf` (named slots for the converted Vue layouts and components).
 */

const TEXT_SCALE: Array<[string, number]> = [
  ["xs", 0.75],
  ["sm", 0.875],
  ["base", 1],
  ["lg", 1.125],
  ["xl", 1.25],
  ["2xl", 1.5],
  ["3xl", 1.875],
  ["4xl", 2.25],
  ["5xl", 3],
  ["6xl", 3.75],
  ["7xl", 4.5],
  ["8xl", 6],
  ["9xl", 8],
];

const fmt = (n: number) => String(Math.round(n * 1000) / 1000);

export function slidevStylesheet(o: {
  scale: number;
  utilities: string;
  helpers: Set<string>;
}): string {
  const px = (n: number) => `${fmt(n * o.scale)}px`;
  const parts: string[] = [];
  parts.push(`/* Slidev, at Kadal's scale — written by \`kadal-deck import slidev\`.

   Slidev draws on a ${fmt(1920 / o.scale)}px-wide canvas with a 16px rem; this deck draws on Kadal's 1920px
   stage, so one Slidev rem is ${px(16)} here. Every length the importer converted is written in it,
   and the utility classes the slides use are defined below in the same unit. Edit freely: nothing
   rewrites this file. */

:root {
  --slidev-rem: ${px(16)};
}

/* Tailwind (the starter's) at the same scale, for any utility it generates that is not below. */
.deck-slide {
  --spacing: calc(var(--slidev-rem) / 4);
${TEXT_SCALE.map(([k, v]) => `  --text-${k}: calc(${v} * var(--slidev-rem));`).join("\n")}
}
`);
  if (o.helpers.has("slidevAnim"))
    parts.push(`/* Slidev's click presets: v-click.fade / .up / .down / .left / .right / .scale / .none, composable.
   (Ported from Slidev's styles/vclick.css, MIT, © Anthony Fu.) */
.deck-click.effect-slidev {
  transition:
    opacity 0.1s ease,
    translate 0.1s ease,
    scale 0.1s ease;
}
.deck-click.effect-slidev.slidev-anim-fade-in {
  transition-duration: 0.3s;
}
.deck-click.effect-slidev.slidev-anim-none {
  transition: none;
}
.deck-click.effect-slidev.is-hidden.slidev-anim-fade {
  opacity: 0.5;
}
.deck-click.effect-slidev.is-hidden.slidev-anim-up {
  translate: 0 ${px(20)};
}
.deck-click.effect-slidev.is-hidden.slidev-anim-down {
  translate: 0 -${px(20)};
}
.deck-click.effect-slidev.is-hidden.slidev-anim-left {
  translate: ${px(20)} 0;
}
.deck-click.effect-slidev.is-hidden.slidev-anim-right {
  translate: -${px(20)} 0;
}
.deck-click.effect-slidev.is-hidden.slidev-anim-scale {
  scale: 0.9;
}
.is-print-all .deck-click.effect-slidev,
.is-tile .deck-click.effect-slidev {
  translate: none !important;
  scale: none !important;
}
@media (prefers-reduced-motion: reduce) {
  .deck-click.effect-slidev {
    transition: none;
  }
}
`);
  if (o.helpers.has("fadeOut"))
    parts.push(`/* Slidev's fade-out transition: the slide leaving fades first, then the next one fades in. */
@keyframes slidev-fade-out-out {
  from {
    opacity: 1;
  }
  60%,
  to {
    opacity: 0;
  }
}
@keyframes slidev-fade-out-in {
  from,
  60% {
    opacity: 0;
  }
  to {
    opacity: 1;
  }
}
`);
  if (o.utilities.trim())
    parts.push(
      `/* The utility classes the slides use (UnoCSS's names; generated by the importer). */\n${o.utilities}\n`,
    );
  return parts.join("\n");
}

const SLIDEV_ON = `
/** Slidev's \`$slidev.nav\` calls, by name: what \`<SlidevOn click="…">\` runs. */
function run(actions: DeckActions, click: string) {
  const go = /^go:(\\d+)$/.exec(click);
  if (go) return actions.gotoFlat(Number(go[1]) - 1);
  switch (click) {
    case "next":
      return actions.next();
    case "prev":
      return actions.prev();
    case "nextSlide":
      return actions.nextSlide();
    case "prevSlide":
      return actions.prevSlide();
    case "first":
      return actions.first();
    case "last":
      return actions.last();
    case "toggleDark":
      return actions.toggleColorScheme();
    case "toggleOverview":
      return actions.toggleOverview();
    case "presenter":
      return actions.openPresenter();
    case "fullscreen":
      return actions.toggleFullscreen();
    case "drawing":
      return actions.toggleDrawing();
  }
}

/**
 * An element that runs a deck action when clicked (or Enter/Space when it is not already a
 * button or link): Slidev's \`<div @click="$slidev.nav.next">\` as \`<SlidevOn click="next">\`.
 */
export function SlidevOn({
  as,
  click,
  children,
  ...rest
}: {
  as?: ElementType;
  click: string;
  children?: ReactNode;
  [key: string]: unknown;
}) {
  const actions = useActions();
  const Tag = (as ?? "div") as ElementType;
  const native = Tag === "button" || Tag === "a";
  return (
    <Tag
      {...(native ? {} : { role: "button", tabIndex: 0 })}
      {...rest}
      onClick={(e: { stopPropagation(): void }) => {
        e.stopPropagation();
        run(actions, click);
      }}
      onKeyDown={
        native
          ? undefined
          : (e: { key: string; preventDefault(): void }) => {
              if (e.key !== "Enter" && e.key !== " ") return;
              e.preventDefault();
              run(actions, click);
            }
      }
    >
      {children}
    </Tag>
  );
}
`;

const SLOTS_OF = `
/**
 * A converted Vue layout's or component's named slots: children marked \`slot="name"\` (a
 * \`<template #name>\` in Slidev) or Kadal's \`::name::\` slot divs (\`data-slot\`), by name; the rest
 * is \`default\`.
 */
export function slotsOf(children: ReactNode): Record<string, ReactNode[]> & { default: ReactNode[] } {
  const out: Record<string, ReactNode[]> & { default: ReactNode[] } = { default: [] };
  for (const child of Children.toArray(children)) {
    const props = isValidElement(child) ? (child.props as Record<string, unknown>) : null;
    const name = (props?.slot ?? props?.["data-slot"]) as string | undefined;
    if (!name || name === "default") {
      if (name === "default") out.default.push(props?.children as ReactNode);
      else out.default.push(child);
      continue;
    }
    (out[name] ??= []).push(props?.children as ReactNode);
  }
  return out;
}
`;

/** src/slidev.tsx, or null when the deck needs none of it. */
export function compatModule(helpers: Set<string>): string | null {
  const on = helpers.has("SlidevOn");
  const slots = helpers.has("slotsOf");
  if (!on && !slots) return null;
  const reactImports = [
    ...(slots ? ["Children", "isValidElement"] : []),
    ...(on ? ["type ElementType"] : []),
    "type ReactNode",
  ];
  return `/**
 * Helpers for what this deck brought from Slidev — written by \`kadal-deck import slidev\`.
 */
${on ? `import { type DeckActions, useActions } from "@kadal/deck";\n` : ""}import { ${reactImports.join(", ")} } from "react";
${on ? SLIDEV_ON : ""}${slots ? SLOTS_OF : ""}`;
}
