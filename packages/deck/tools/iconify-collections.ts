#!/usr/bin/env bun
/**
 * Refreshes src/icons/collections.ts — the Iconify set prefixes the compiler knows, which decide
 * whether `<abc-def />` in a slide is an icon — from Iconify's public API. Run it now and then;
 * a set missing from the list still works through `<Icon name="set:icon" />`, only its tag form
 * stays an ordinary element until the list knows the prefix.
 *
 *   bun tools/iconify-collections.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const out = resolve(import.meta.dirname, "..", "src", "icons", "collections.ts");
const res = await fetch("https://api.iconify.design/collections?hidden=true");
if (!res.ok) throw new Error(`api.iconify.design answered ${res.status}`);
const keys = Object.keys((await res.json()) as Record<string, unknown>)
  .filter((k) => /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(k))
  .sort();

const lines: string[] = [];
let line = "";
for (const k of keys) {
  if (`${line} ${k}`.length > 92) {
    lines.push(line.trim());
    line = "";
  }
  line += ` ${k}`;
}
lines.push(line.trim());

writeFileSync(
  out,
  `/**
 * Every icon set Iconify publishes, by prefix — what tells \`<mdi-account />\` (an icon) from
 * \`<my-widget />\` (a custom element) in a slide, and how \`<simple-icons-github />\` splits into
 * the set \`simple-icons\` and the icon \`github\` rather than \`simple\` and \`icons-github\`.
 *
 * Generated by \`bun tools/iconify-collections.ts\` from https://api.iconify.design/collections
 * (hidden sets included, so old decks keep resolving): ${keys.length} sets, ${new Date().toISOString().slice(0, 10)}.
 * Only the prefixes are kept — this file is part of the compiler, which the hosted shell runs in
 * the browser, so it stays a few kilobytes.
 */
const LIST = [
${lines.map((l) => `  ${JSON.stringify(l)}`).join(",\n")},
].join(" ");

export const ICONIFY_PREFIXES: ReadonlySet<string> = new Set(LIST.split(" "));
`,
);
console.log(`${keys.length} Iconify sets → ${out}`);
