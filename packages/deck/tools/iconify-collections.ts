#!/usr/bin/env bun
/**
 * Refreshes src/icons/collections.ts — the Iconify set prefixes the compiler knows, which decide
 * whether `<abc-def />` in a slide is an icon — from Iconify's public API. Run it now and then;
 * a set missing from the list still works through `<Icon name="set:icon" />`, only its tag form
 * stays an ordinary element until the list knows the prefix.
 *
 *   bun tools/iconify-collections.ts
 *
 * It also writes src/icons/licences.ts: each set's name, licence (SPDX) and author, which the
 * credits slide (credits/collect.ts) names for every set a deck draws icons from.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const out = resolve(import.meta.dirname, "..", "src", "icons", "collections.ts");
const res = await fetch("https://api.iconify.design/collections?hidden=true");
if (!res.ok) throw new Error(`api.iconify.design answered ${res.status}`);
const all = (await res.json()) as Record<
  string,
  { name?: string; author?: { name?: string }; license?: { spdx?: string; title?: string } }
>;
const keys = Object.keys(all)
  .filter((k) => /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(k))
  .sort();

const lines: string[] = [];
let line = "";
for (const k of keys) {
  if (`${line} ${k}`.length > 92) {
    lines.push(line.trim());
    line = "";
  }
  line += ` ${k}`;
}
lines.push(line.trim());

writeFileSync(
  out,
  `/**
 * Every icon set Iconify publishes, by prefix — what tells \`<mdi-account />\` (an icon) from
 * \`<my-widget />\` (a custom element) in a slide, and how \`<simple-icons-github />\` splits into
 * the set \`simple-icons\` and the icon \`github\` rather than \`simple\` and \`icons-github\`.
 *
 * Generated by \`bun tools/iconify-collections.ts\` from https://api.iconify.design/collections
 * (hidden sets included, so old decks keep resolving): ${keys.length} sets, ${new Date().toISOString().slice(0, 10)}.
 * Only the prefixes are kept — this file is part of the compiler, which the hosted shell runs in
 * the browser, so it stays a few kilobytes.
 */
const LIST = [
${lines.map((l) => `  ${JSON.stringify(l)}`).join(",\n")},
].join(" ");

export const ICONIFY_PREFIXES: ReadonlySet<string> = new Set(LIST.split(" "));
`,
);
console.log(`${keys.length} Iconify sets → ${out}`);

// One line a set, "prefix|name|licence|author": the credits name the set, its licence and maker.
const clean = (v: unknown) => (typeof v === "string" ? v.replace(/[|\n]/g, " ").trim() : "");
const rows = keys.map((k) => {
  const s = all[k]!;
  return [
    k,
    clean(s.name) || k,
    clean(s.license?.spdx) || clean(s.license?.title),
    clean(s.author?.name),
  ].join("|");
});
const licences = resolve(import.meta.dirname, "..", "src", "icons", "licences.ts");
writeFileSync(
  licences,
  `/**
 * Every Iconify set's name, licence (SPDX) and author, by prefix — what the credits slide says
 * for each set a deck draws icons from (credits/collect.ts). Generated by
 * \`bun tools/iconify-collections.ts\` from https://api.iconify.design/collections:
 * ${keys.length} sets, ${new Date().toISOString().slice(0, 10)}. A set's page is
 * https://icon-sets.iconify.design/<prefix>/.
 */
const ROWS = ${JSON.stringify(rows.join("\n"))};

export interface IconSetInfo {
  prefix: string;
  name: string;
  /** SPDX id ("MIT", "CC-BY-4.0"), or the set's own licence title when it has no SPDX id. */
  licence: string;
  author: string;
}

let table: Map<string, IconSetInfo> | null = null;

/** A set's name, licence and author; null for a prefix Iconify did not list. */
export function iconSetInfo(prefix: string): IconSetInfo | null {
  table ??= new Map(
    ROWS.split("\\n").map((row) => {
      const [p, name, licence, author] = row.split("|") as [string, string, string, string];
      return [p, { prefix: p, name, licence, author }];
    }),
  );
  return table.get(prefix) ?? null;
}
`,
);
console.log(`${keys.length} set licences → ${licences}`);
